export const getMonumentImage = (monument: { id?: string; title?: string; image_url?: string | null }): string => {
  if (monument.image_url && monument.image_url.startsWith('/images/monuments/') && !monument.image_url.includes('generic') && !monument.image_url.includes('destination-featured')) {
    return monument.image_url;
  }
  const key = (monument.title || '').toLowerCase().replace(/['"]/g, '').trim();
  if (MONUMENT_IMAGE_MAP[key]) {
    return MONUMENT_IMAGE_MAP[key];
  }
  if (monument.image_url) {
    return monument.image_url;
  }
  return '/images/monuments/konark-temple.jpg';
};

